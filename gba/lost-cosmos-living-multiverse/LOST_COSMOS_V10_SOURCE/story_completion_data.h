/* Runtime contracts, independent of the existing trigger numbers.
 * DIALOGUE: speak to distinct inhabitants and resolve a negotiation.
 * MIRROR: align physical reflection fixtures before the next station.
 * TRUST: a local guardian must be fought or peacefully settled.
 * RESTORE: use an earned old relic and perform a local healing action.
 * SEQUENCE: operate geographically separated runes in the given order.
 * RHYTHM: perform an input at a visible musical timing window.
 * TRAVERSE: cross an authored causeway or stepping-stone route.
 * ENCOUNTER: earn a local encounter victory after accepting the quest.
 * BOSS: earn three separate local battle phases, never reuse global kills.
 * CLOCK: restore two physical anchors and settle a temporal encounter.
 */
