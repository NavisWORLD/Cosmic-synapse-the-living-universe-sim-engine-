"""Original Lost COSMOS native pixel art, authored for this project.

Editable indexed pixels: '.' is transparent, 1..9/A..F are palette indices.
Every creature is a separate 16x16 drawing; evolution changes anatomy.
No artwork, sprites or tiles were copied from other games. The compiler is
visual_assets_v10_8.py. This module contains the art, not gameplay rules.
"""

from __future__ import annotations


def pixels(text: str, width: int = 16, height: int = 16) -> list[list[int]]:
    rows = [r.strip() for r in text.strip().splitlines()]
    if len(rows) != height or any(len(r) > width for r in rows):
        raise ValueError(f"Invalid {width}x{height} pattern: {[len(r) for r in rows]}")
    return [[0 if c == "." else int(c, 16) for c in r.ljust(width, ".")] for r in rows]


def redraw(src: list[list[int]], changes: dict[int, str]) -> list[list[int]]:
    result = [r[:] for r in src]
    for y, row in changes.items():
        if len(row) > len(src[0]):
            raise ValueError("Redraw exceeds sprite width")
        result[y] = [0 if c == "." else int(c, 16) for c in row.ljust(len(src[0]), ".")]
    return result


