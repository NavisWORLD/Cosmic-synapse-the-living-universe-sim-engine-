def hero_frames(base: list[list[int]], side: bool = False) -> list[list[list[int]]]:
    # Whole leg poses and moving scarf, rather than an isolated flashing pixel.
    a = redraw(base, {12: "....1255521.....", 13: "....15511551....",
                      14: "....1D1..1D1....", 15: "....111..111...."})
    b = redraw(base, {12: ".....12521......", 13: ".....15551......",
                      14: "......1DD1......", 15: "......1111......"})
    c = redraw(base, {12: ".....125521.....", 13: ".....1551151....",
                      14: ".....1D1.1D1....", 15: ".....111.111...."})
    if side:
        a = redraw(a, {7: "...1AA1B11......", 8: "..1AB.23321....."})
        b = redraw(b, {7: "....1A1B11......", 8: "...1AB23321....."})
        c = redraw(c, {7: "..1AAA1B11......", 8: "...1B.23321....."})
    else:
        a = redraw(a, {7: "....1ABA11......"})
        b = redraw(b, {7: ".....1BA11......"})
        c = redraw(c, {7: ".....1BAA1......"})
    return [base, a, b, c]


