class Canvas:
    """Exact indexed-pixel primitives for hand-designed larger set pieces."""

    def __init__(self, w: int, h: int, fill: int = 9):
        self.w, self.h = w, h
        self.p = [[fill] * w for _ in range(h)]

    def dot(self, x: int, y: int, c: int) -> None:
        if 0 <= x < self.w and 0 <= y < self.h:
            self.p[y][x] = c

    def rect(self, x: int, y: int, w: int, h: int, c: int) -> None:
        for yy in range(y, y+h):
            for xx in range(x, x+w):
                self.dot(xx, yy, c)

    def line(self, x0: int, y0: int, x1: int, y1: int, c: int) -> None:
        dx, dy, n = x1-x0, y1-y0, max(abs(x1-x0), abs(y1-y0))
        for i in range(n+1):
            self.dot(x0+(dx*i)//max(n, 1), y0+(dy*i)//max(n, 1), c)

    def poly(self, coords: list[tuple[int, int]], c: int) -> None:
        for y in range(self.h):
            edges = []
            for (x0, y0), (x1, y1) in zip(coords, coords[1:]+coords[:1]):
                if min(y0, y1) <= y < max(y0, y1):
                    edges.append(x0+(x1-x0)*(y-y0)/(y1-y0))
            edges.sort()
            for x0, x1 in zip(edges[::2], edges[1::2]):
                for x in range(int(x0+.999), int(x1)+1):
                    self.dot(x, y, c)

    def ellipse(self, x: int, y: int, w: int, h: int, c: int) -> None:
        for yy in range(y, y+h):
            for xx in range(x, x+w):
                if ((2*(xx-x)+1-w)**2)/(w*w)+((2*(yy-y)+1-h)**2)/(h*h) <= 1:
                    self.dot(xx, yy, c)


def ground(c: Canvas) -> None:
    # Sparse clustered ground flecks at known hand-placed coordinates.
    for x, y in [(2,c.h-3), (c.w-5,c.h-2), (c.w-7,c.h-5), (4,c.h-8)]:
        c.line(x, y, x+1, y-1, 11)


def leaf_lobe(c: Canvas, x: int, y: int, w: int, h: int) -> None:
    # Overlapping scallops create an irregular crown, not an ellipse sprite.
    c.ellipse(x, y, w, h, 13)
    c.ellipse(x+1, y, w-2, h-2, 1)
    c.ellipse(x+1, y, w-3, h-4, 2)
    c.ellipse(x+2, y+1, max(2,w-6), max(2,h-6), 3)
    c.line(x+3, y+2, x+min(6,w-3), y+2, 4)
    c.line(x+2, y+3, x+3, y+3, 3)
    # Leaf clusters are deliberate two- and three-pixel strokes following the
    # crown's contour, with small shadow notches below the lower leaves.
    c.line(x+w-5,y+4,x+w-3,y+4,3)
    c.dot(x+w-4,y+3,4)
    c.line(x+3,y+h-5,x+5,y+h-5,2)
    c.line(x+5,y+h-4,x+7,y+h-4,1)
    c.dot(x+4,y+h-6,3)
    c.line(x+w-5,y+h-5,x+w-3,y+h-5,1)


