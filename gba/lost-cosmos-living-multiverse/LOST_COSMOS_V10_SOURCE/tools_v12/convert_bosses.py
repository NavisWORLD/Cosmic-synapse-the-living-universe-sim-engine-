#!/usr/bin/env python3
"""V12.3 boss converter. Cosmo's 64x64 4bpp boss sheets (v12_assets/bosses, copied from
cosmo-study/gba_bosses: Grumbleback v2.1, Forest Guardian v2.2) -> one raw 2 KB block per
frame (64 tiles, 1D OBJ order) so the cartridge streams exactly one frame per tick with a
single DMA3 transfer. Palettes are Cosmo's .bin (BGR555) verbatim. Also emits procedural
PLACEHOLDER art for the Guardian Statues (no Cosmo sprite yet). Writes v12_boss.c/.h."""
import json
from pathlib import Path
from PIL import Image
R=Path(__file__).resolve().parent.parent; B=R/'v12_assets'/'bosses'
M=json.load(open(B/'boss_frame_map.json'))
C=['typedef unsigned int u32;typedef unsigned short u16;typedef unsigned char u8;']
H=['/* GENERATED by tools_v12/convert_bosses.py. Do not edit. */','#ifndef V12_BOSS_H','#define V12_BOSS_H',
   'typedef struct{u8 first,count,div,loop;}V12BossAnim;']
def tile(px,w,x0,y0):
    out=[]
    for y in range(8):
        v=0
        for x in range(8): v|=(px[(y0+y)*w+x0+x]&15)<<(4*x)
        out.append(v)
    return out
for bid,sym in [('boss_grumbleback','grumbleback'),('boss_forest_guardian','guardian'),('boss_guardian_statues','statue')]:
    m=M[bid]; im=Image.open(B/f'{bid}.png'); assert im.mode=='P'; w,h=im.size; px=im.tobytes()
    words=[];anims=[];names=[];n=0
    for an,a in m['animations'].items():
        anims.append((n,a['frame_count'],max(1,60//a['fps_suggest']),1 if a['loop'] else 0)); names.append(an)
        for f in a['frames']:
            for ty in range(8):
                for tx in range(8): words+=tile(px,w,f['x']+tx*8,f['y']+ty*8)
            n+=1
    assert len(words)==n*512
    pal=open(B/f'{bid}.bin','rb').read(); pal=[pal[i]|(pal[i+1]<<8) for i in range(0,32,2)]
    C.append(f'const u32 v12_boss_{sym}_frames[{len(words)}]={{'+','.join(f'0x{x:08X}u' for x in words)+'};')
    C.append(f'const u16 v12_boss_{sym}_pal[16]={{'+','.join(f'0x{x:04X}' for x in pal)+'};')
    H.append(f'extern const u32 v12_boss_{sym}_frames[{len(words)}];extern const u16 v12_boss_{sym}_pal[16];')
    H.append(f'#define V12_BOSS_{sym.upper()}_FRAMES {n}')
    H.append(f'static const V12BossAnim V12_BOSS_{sym.upper()}_ANIM[{len(anims)}]={{'+','.join('{%d,%d,%d,%d}'%a for a in anims)+'};')
    for k,an in enumerate(names): H.append(f'#define BA_{sym.upper()}_{an.upper()} {k}')
    print(bid,'frames',n,'bytes',n*2048,'anims',names)
# Guardian Statues lane art (Cosmo, top-down): 16x16 warning tile x4, 64x32 telegraph arc x4,
# 64x32 swing arc x6. A gameplay lane is 32 px = two 16 px tiles side by side.
LM=M['boss_guardian_statues_lane']['assets']
for key,sym in [('lane_warning_tile_16','warn'),('halberd_sweep_telegraph_64x32','tele'),('halberd_sweep_swing_64x32','swing')]:
    a_=LM[key]; im=Image.open(B/Path(a_['sheet']).name); assert im.mode=='P'; w,h=im.size; px=im.tobytes(); fw,fh=a_['frame_size']; words=[]
    for f in a_['frames']:
        for ty in range(fh//8):
            for tx in range(fw//8): words+=tile(px,w,f['x']+tx*8,f['y']+ty*8)
    C.append(f'const u32 v12_lane_{sym}[{len(words)}]={{'+','.join(f'0x{x:08X}u' for x in words)+'};')
    H.append(f'extern const u32 v12_lane_{sym}[{len(words)}];')
H.append('#endif')
(R/'v12_boss.c').write_text('/* GENERATED by tools_v12/convert_bosses.py. Do not edit. */\n'+'\n'.join(C)+'\n')
(R/'v12_boss.h').write_text('\n'.join(H)+'\n')
