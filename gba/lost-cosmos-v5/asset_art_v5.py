def grid(a):
 assert len(a)==16 and all(len(row)==16 for row in a),(len(a),[len(x) for x in a]);return [[int(ch,16) for ch in row] for row in a]
def pack_bg(rows):
 assert len(rows)==8 and all(len(x)==8 for x in rows)
 return [sum(int(ch,16)<<(4*x) for x,ch in enumerate(row)) for row in rows]
def pack_sprite(p):
 p=grid(p)
 return [sum(p[ty*8+y][tx*8+x]<<(4*x) for x in range(8)) for ty in range(2) for tx in range(2) for y in range(8)]

