def emit_array(name,groups,chunk):
 lines=[f'static const u32 {name}[{len(groups)}][{chunk}] = {{']
 for arr in groups:
  assert len(arr)==chunk
  lines.append(' {'+','.join('0x%08Xu'%x for x in arr)+'},')
 lines.append('};')
 return '\n'.join(lines)

